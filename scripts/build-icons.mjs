#!/usr/bin/env node
/* Build components/assets/icons.js from the icon vocabulary (components/icons/names.json) and every icon set in it.
   Output: window.S4_ICONS = { set, viewBox, credit, icons, sets: { id: { label, viewBox, credit, icons: { semanticName: svgBody } } } }.
   `set`, `viewBox`, `credit` and `icons` describe the active set (names.json "set"); S4.icon.use(id) switches at run time.
   Apps can also register more at run time with S4.icon.add({ name: body }).
   Usage: node scripts/build-icons.mjs [--check] */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(readFileSync(join(root, 'components/icons/names.json'), 'utf8'));
const sets = {}, missing = [];
for (const [id, set] of Object.entries(cfg.sets)) {
  const source = JSON.parse(readFileSync(join(root, set.source), 'utf8'));
  const icons = {};
  for (const [name, iconId] of Object.entries(set.names)) source[iconId] ? (icons[name] = source[iconId]) : missing.push(`${id}: ${name} -> ${iconId}`);
  sets[id] = { label: set.label, viewBox: set.viewBox, credit: set.credit, icons };
}
if (missing.length) { console.error('Missing icons:\n  ' + missing.join('\n  ')); process.exit(1); }
const active = sets[cfg.set];
const out = `/* S4 Orion icons. GENERATED by scripts/build-icons.mjs from components/icons/names.json. Do not edit.
   Sets: ${Object.keys(sets).join(', ')} (active: ${cfg.set}). Credit the set in use on published pages. */
window.S4_ICONS = ${JSON.stringify({ set: cfg.set, viewBox: active.viewBox, credit: active.credit, icons: active.icons, sets })};
`;
const file = join(root, 'components/assets/icons.js');
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== out) { console.error('Stale components/assets/icons.js (run npm run build:icons)'); process.exit(1); }
  console.log(`Icons up to date: ${Object.keys(active.icons).length} names, ${Object.keys(sets).length} sets`);
} else { writeFileSync(file, out); console.log(`Built ${Object.keys(active.icons).length} icons in ${Object.keys(sets).length} sets -> components/assets/icons.js (${(out.length / 1024).toFixed(0)} KB)`); }
